#!/usr/bin/env node
// Assemble an npm package from build outputs and `npm pack` it.
//
//   node scripts/pack.mjs native <out-dir> <native-x64-dir> <native-arm64-dir>
//   node scripts/pack.mjs wasm   <out-dir> <wasm-st-dir> <wasm-mt-dir>
//
// Writes <out-dir>/libjxl-<kind>-<LIBJXL_VERSION>-<PACKAGE_REVISION>.tgz
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

function readEnv(file) {
  const env = {};
  for (const line of fs.readFileSync(file, 'utf8').split('\n')) {
    const m = line.match(/^([A-Z_]+)=(.*)$/);
    if (m) env[m[1]] = m[2].trim();
  }
  return env;
}

function sameTree(a, b) {
  const list = (d) =>
    fs.readdirSync(d, { recursive: true }).filter((f) => fs.statSync(path.join(d, f)).isFile()).sort();
  const la = list(a);
  const lb = list(b);
  return (
    JSON.stringify(la) === JSON.stringify(lb) &&
    la.every((f) => fs.readFileSync(path.join(a, f)).equals(fs.readFileSync(path.join(b, f))))
  );
}

function copy(from, to) {
  fs.cpSync(from, to, { recursive: true, dereference: true });
}

// TypeScript declarations for an Emscripten module whose exports are listed
// one C symbol per line in <name>.exports.
function moduleTypes(exportsFile, threads) {
  const names = fs.readFileSync(exportsFile, 'utf8').split('\n').filter(Boolean);
  const fns = ['malloc', 'free', ...names]
    .map((n) => `  _${n}(...args: number[]): number;`)
    .join('\n');
  return `// Generated by scripts/pack.mjs. Every C function takes and returns
// numbers (pointers are byte offsets into HEAPU8, a wasm32 size_t is 32-bit).
export interface LibjxlModule {
${fns}
  HEAP8: Int8Array;
  HEAPU8: Uint8Array;
  HEAP16: Int16Array;
  HEAPU16: Uint16Array;
  HEAP32: Int32Array;
  HEAPU32: Uint32Array;
  HEAPF32: Float32Array;
  HEAPF64: Float64Array;
  getValue(ptr: number, type?: string): number;
  setValue(ptr: number, value: number, type?: string): void;
  UTF8ToString(ptr: number, maxBytesToRead?: number): string;
  stringToUTF8(str: string, outPtr: number, maxBytesToWrite: number): void;
  lengthBytesUTF8(str: string): number;
  addFunction(fn: (...args: any[]) => any, signature: string): number;
  removeFunction(ptr: number): void;
}

export interface LibjxlModuleOptions {
  /** Override where the .wasm file is loaded from. */
  locateFile?(path: string, prefix: string): string;
  /** Pass a precompiled module or bytes instead of fetching. */
  wasmBinary?: ArrayBuffer | Uint8Array;
  [key: string]: unknown;
}

/** Instantiate the ${threads ? 'multi-threaded (pthreads)' : 'single-threaded'} libjxl module. */
export default function createLibjxl(options?: LibjxlModuleOptions): Promise<LibjxlModule>;
`;
}

const [kind, outDir, ...inputs] = process.argv.slice(2);
const env = readEnv(path.join(root, 'build.env'));
const version = `${env.LIBJXL_VERSION}-${env.PACKAGE_REVISION}`;
const stage = fs.mkdtempSync(path.join(os.tmpdir(), `libjxl-${kind}-`));
const template = path.join(root, 'packages', kind);

if (kind === 'native') {
  const [x64, arm64] = inputs.map((p) => path.resolve(p));
  for (const sub of ['include', 'licenses']) {
    if (!sameTree(path.join(x64, sub), path.join(arm64, sub))) {
      throw new Error(`${sub}/ differs between x64 and arm64 builds`);
    }
  }
  for (const f of ['index.js', 'index.d.ts', 'README.md']) copy(path.join(template, f), path.join(stage, f));
  copy(path.join(x64, 'lib'), path.join(stage, 'lib', 'linux-x64'));
  copy(path.join(arm64, 'lib'), path.join(stage, 'lib', 'linux-arm64'));
  copy(path.join(x64, 'include'), path.join(stage, 'include'));
  copy(path.join(x64, 'licenses'), path.join(stage, 'licenses'));
} else if (kind === 'wasm') {
  const [st, mt] = inputs.map((p) => path.resolve(p));
  for (const sub of ['include', 'licenses']) {
    if (!sameTree(path.join(st, sub), path.join(mt, sub))) {
      throw new Error(`${sub}/ differs between st and mt builds`);
    }
  }
  copy(path.join(template, 'README.md'), path.join(stage, 'README.md'));
  copy(path.join(st, 'include'), path.join(stage, 'include'));
  copy(path.join(st, 'licenses'), path.join(stage, 'licenses'));
  fs.mkdirSync(path.join(stage, 'dist'));
  for (const [dir, name, threads] of [[st, 'libjxl', false], [mt, 'libjxl-mt', true]]) {
    for (const ext of ['.js', '.wasm']) {
      copy(path.join(dir, 'dist', name + ext), path.join(stage, 'dist', name + ext));
    }
    fs.writeFileSync(
      path.join(stage, 'dist', `${name}.d.ts`),
      moduleTypes(path.join(dir, 'dist', `${name}.exports`), threads),
    );
  }
} else {
  throw new Error(`unknown package kind: ${kind}`);
}

const pkg = JSON.parse(fs.readFileSync(path.join(template, 'package.json'), 'utf8'));
pkg.version = version;
pkg.libjxl = { version: env.LIBJXL_VERSION, commit: env.LIBJXL_COMMIT };
if (kind === 'wasm') pkg.libjxl.emscripten = env.EMSDK_VERSION;
fs.writeFileSync(path.join(stage, 'package.json'), JSON.stringify(pkg, null, 2) + '\n');

fs.mkdirSync(outDir, { recursive: true });
const dest = path.resolve(outDir);
const [{ filename }] = JSON.parse(
  execFileSync('npm', ['pack', '--json', '--pack-destination', dest], { cwd: stage, encoding: 'utf8' }),
);
const expected = `libjxl-${kind}-${version}.tgz`;
if (path.basename(filename) !== expected) {
  fs.renameSync(path.join(dest, path.basename(filename)), path.join(dest, expected));
}
fs.rmSync(stage, { recursive: true, force: true });
console.log(path.join(dest, expected));
